import assert from 'node:assert/strict';
import {audit} from '../lib/audit.mjs';
import {newPlan,flightResults} from '../lib/flight.mjs';
import {selectWeather,fetchPagesWeather} from '../lib/pages-weather.mjs';
const now=Date.parse('2026-10-14T12:00:00Z');
const snapshot={version:1,retrievedAt:'2026-10-14T11:50:00Z',source:'NOAA',sourceUrl:'https://aviationweather.gov/data/api/',metars:[{icaoId:'LFPO',rawOb:'original'},{icaoId:'KJFK'}],tafs:[{icaoId:'LFPO',rawTAF:'original TAF'}],errors:[]};
const filtered=selectWeather(snapshot,['LFPO','LFPN'],now);
assert.deepEqual(filtered.metars,[snapshot.metars[0]]);
assert.deepEqual(filtered.tafs,snapshot.tafs);
assert.equal(filtered.retrievedAt,snapshot.retrievedAt);
assert.equal(filtered.errors.length,0);
assert.equal(selectWeather(snapshot,['LFPN'],now).metars.length,0);
assert.match(selectWeather(snapshot,[],now+60*60000).errors[0],/ancien/);
assert.match(selectWeather(snapshot,[],now-30*60000).errors[0],/incohérent/);
assert.throws(()=>selectWeather({...snapshot,retrievedAt:'invalid'},[]),/invalide/);
await assert.rejects(fetchPagesWeather([], 'weather.json',async()=>({ok:false})),/indisponible/);
let options;
await fetchPagesWeather(['LFPO'],'weather.json',async(url,o)=>{options=o;assert.match(url,/weather.json\?t=/);return {ok:true,json:async()=>snapshot}});
assert.equal(options.cache,'no-store');
const plan=newPlan();plan.weather=filtered;assert(audit(plan,flightResults(plan),now+60*60000).some(x=>x.includes('Snapshot météo âgé')));
console.log('12 contrôles météo statique réussis.');
